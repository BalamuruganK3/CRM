export async function initDatabase() {
  await waitForDatabase();
  for (const statement of schema) {
    await pool.query(statement);
  }
  await pool.query('ALTER TABLE ui_elements ADD COLUMN IF NOT EXISTS icon_size INT NULL');
  await pool.query('ALTER TABLE ui_elements ADD COLUMN IF NOT EXISTS text_size INT NULL');
  await pool.query('ALTER TABLE projects ADD COLUMN IF NOT EXISTS start_date DATE');
  await pool.query('ALTER TABLE projects ADD COLUMN IF NOT EXISTS end_date DATE');

  const tables = ['users', 'projects', 'project_assignments', 'modules', 'updates', 'files', 'ui_elements'];
  for (const table of tables) {
    await pool.query(`ALTER TABLE ${table} ENABLE ROW LEVEL SECURITY`);
    // await pool.query(`REVOKE ALL ON TABLE ${table} FROM anon, authenticated`);
  }

  const passwordHash = bcrypt.hashSync('password123', 10);
  const people = [
    ['developer', 'developer@projects.local', passwordHash, 'Developer', 'developer', 0],
    ['manager1', 'manager1@projects.local', passwordHash, 'Morgan Hale', 'manager', 1],
    ['employee1', 'employee1@projects.local', passwordHash, 'Avery Cole', 'employee', 1],
    ['employee2', 'employee2@projects.local', passwordHash, 'Riley Shah', 'employee', 1],
  ];
  for (const person of people) {
    const [existing] = await pool.query('SELECT id FROM users WHERE username = ? LIMIT 1', [person[0]]);
    if (!existing.length) {
      await pool.query(
        'INSERT INTO users (username, email, password_hash, full_name, role, is_demo) VALUES (?, ?, ?, ?, ?, ?)',
        person,
      );
    } else {
      await pool.query('UPDATE users SET password_hash = ? WHERE username = ?', [passwordHash, person[0]]);
    }
  }

  const [userCount] = await pool.query('SELECT COUNT(*) AS count FROM users');
  const [projectCount] = await pool.query('SELECT COUNT(*) AS count FROM projects');
  if (Number(userCount[0].count) && Number(projectCount[0].count) === 0) {
    // Seed demo projects only when accounts exist but no projects have been created yet.

    const [managers] = await pool.query("SELECT id FROM users WHERE username = 'manager1'");
    const [employeeOne] = await pool.query("SELECT id FROM users WHERE username = 'employee1'");
    const [employeeTwo] = await pool.query("SELECT id FROM users WHERE username = 'employee2'");
    const managerId = managers[0].id;
    const firstEmployee = employeeOne[0].id;
    const secondEmployee = employeeTwo[0].id;

    const [projectOne] = await pool.query(
      `INSERT INTO projects (name, idea, manager_instructions, status, created_by, is_demo)
       VALUES (?, ?, ?, 'ongoing', ?, 1) RETURNING id`,
      [
        'Customer onboarding portal',
        'A guided portal where new customers finish account setup and see what happens next.',
        'Keep each module small. After you change a screen, post a screenshot and a short note so the review stays easy to follow.',
        managerId,
      ],
    );
    const [projectTwo] = await pool.query(
      `INSERT INTO projects (name, idea, manager_instructions, status, created_by, is_demo)
       VALUES (?, ?, ?, 'not_started', ?, 1) RETURNING id`,
      [
        'Field visit tracker',
        'A simple record of site visits, what was found, and what should happen next.',
        'Leave this in Others until the first visit is scheduled. Then add one module per visit.',
        managerId,
      ],
    );

    await pool.query('INSERT INTO project_assignments (project_id, user_id) VALUES (?, ?), (?, ?), (?, ?)', [
      projectOne.insertId, firstEmployee,
      projectOne.insertId, secondEmployee,
      projectTwo.insertId, firstEmployee,
    ]);

    const [moduleRow] = await pool.query(
      'INSERT INTO modules (project_id, title, created_by, is_demo) VALUES (?, ?, ?, 1) RETURNING id',
      [projectOne.insertId, 'Account setup checklist', firstEmployee],
    );
    await pool.query(
      'INSERT INTO updates (module_id, user_id, note, is_demo) VALUES (?, ?, ?, 1)',
      [moduleRow.insertId, firstEmployee, 'Started the account setup checklist and listed the first three screens.'],
    );
  }

  const [uiCount] = await pool.query('SELECT COUNT(*) AS count FROM ui_elements');
  if (Number(uiCount[0].count) === 0) {
    for (const row of uiSeed) {
      await pool.query(
        `INSERT INTO ui_elements (page, slot, element_key, element_type, content, icon, action_key, sort_order)
         VALUES (?, ?, ?, ?, ?, ?, ?, ?)`,
        row,
      );
    }
  }

  const ensured = uiSeed.filter((row) => ['brand', 'back_to_top', 'theme_accent', 'theme_paper', 'theme_ink', 'theme_card', 'field_shape', 'button_shape', 'icon_size', 'field_size', 'start_date_label', 'end_date_label', 'updates_heading', 'update_placeholder', 'upload_label', 'post_update', 'update_required'].includes(row[2]));
  for (const row of ensured) {
    await pool.query(
      `INSERT INTO ui_elements (page, slot, element_key, element_type, content, icon, action_key, sort_order)
       SELECT ?, ?, ?, ?, ?, ?, ?, ?
       WHERE NOT EXISTS (SELECT 1 FROM ui_elements WHERE page = ? AND element_key = ?)
       ON CONFLICT (page, element_key) DO NOTHING`,
      [...row, row[0], row[2]],
    );
  }
}
